#!/usr/bin/env bash

#
# ======================== 0. 开启严格模式 ========================
#
set -euo pipefail

#
# ======================== 1. 进入项目目录 ========================
#
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."

#
# ======================== 2. 设置关闭参数 ========================
#
# IS_DOCKER_CLEAN  用于设置关闭服务后是否需要执行清理（通过命令参数获取）
#
IS_DOCKER_CLEAN="1"  # 1：是 | 0：否 | 默认：1

#
# ======================== 3. 解析命令参数 ========================
#
while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-clean)
      IS_DOCKER_CLEAN="0"
      shift
      ;;
    *)
      echo "错误：参数 $1 不支持！" >&2
      exit 1
      ;;
  esac
done

#
# ======================== 4. 校验环境变量 ========================
#
[[ -f .env ]] || {
  echo "错误：文件 .env 不存在，请先启动服务！" >&2
  exit 1
}

#
# ======================== 5. 执行关闭服务 ========================
#
COMPOSE=(docker compose -f compose.yaml --env-file .env)

if [[ "${IS_DOCKER_CLEAN}" == "1" ]]; then
  "${COMPOSE[@]}" down --rmi all
else
  "${COMPOSE[@]}" down
fi

#
# ======================== 6. 输出结果日志 ========================
#
docker ps
