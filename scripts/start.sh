#!/usr/bin/env bash

#
# ======================== 0. 开启严格模式 ========================
#
set -euo pipefail

#
# ======================== 1. 进入项目目录 ========================
#
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."

#
# ======================== 2. 设置环境变量 ========================
#

#
# ======================== 3. 校验环境变量 ========================
#

#
# ======================== 4. 设置命令参数 ========================
#
# IS_DOCKER_BUILD  用于设置服务启动时是否构建镜像（1：是 | 0：否）
#
IS_DOCKER_BUILD="0"

#
# ======================== 5. 解析命令参数 ========================
#
while [[ $# -gt 0 ]]; do
  case "$1" in
    --build)
      IS_DOCKER_BUILD="1"
      shift
      ;;
    *)
      echo "错误：参数 $1 不支持！" >&2
      exit 1
      ;;
  esac
done

#
# ======================== 6. 校验命令参数 ========================
#

#
# ======================== 7. 创建环境变量 ========================
#
cat > .env <<EOF
EOF

#
# ======================== 8. 执行启动服务 ========================
#
COMPOSE=(docker compose -f compose.yaml --env-file .env)

[[ "${IS_DOCKER_BUILD}" == "1" ]] && {
  "${COMPOSE[@]}" build
}

"${COMPOSE[@]}" up -d --no-build

#
# ======================== 9. 输出结果日志 ========================
#
docker ps
