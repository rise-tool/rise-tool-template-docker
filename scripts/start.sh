#!/usr/bin/env bash

#
# ======================== 0. 开启严格模式 ========================
#
set -euo pipefail

#
# ======================== 1. 进入项目目录 ========================
#
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."

#
# ======================== 2. 设置启动参数 ========================
#
# IS_DOCKER_BUILD  用于设置服务启动时是否需要构建镜像（通过命令参数获取）
#
IS_DOCKER_BUILD="1"  # 1：是 | 0：否 | 默认：1

#
# ======================== 3. 解析命令参数 ========================
#
while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-build)
      IS_DOCKER_BUILD="0"
      shift
      ;;
    *)
      echo "错误：参数 $1 不支持！" >&2
      exit 1
      ;;
  esac
done

#
# ======================== 4. 校验必填参数 ========================
#

#
# ======================== 5. 校验参数合法 ========================
#

#
# ======================== 6. 创建环境变量 ========================
#
cat > .env <<EOF
EOF

#
# ======================== 7. 执行启动服务 ========================
#
COMPOSE=(docker compose -f compose.yaml --env-file .env)

[[ "${IS_DOCKER_BUILD}" == "1" ]] && {
  "${COMPOSE[@]}" build
}

"${COMPOSE[@]}" up -d --no-build

#
# ======================== 8. 输出结果日志 ========================
#
docker ps
